"""Correct proposed plans using trusted counts; never execute proposed analyses."""

from copy import deepcopy

from pydantic import ConfigDict, JsonValue, TypeAdapter

from app.analysis_selection import select_analyses
from app.tool_schemas import (
    AnalysisPlan,
    AttributeAnalysisCounts,
    GuardedAnalysisPlan,
    PlanCorrection,
)

_JSON_VALUE = TypeAdapter(
    JsonValue, config=ConfigDict(strict=True, allow_inf_nan=False),
)
_DEFAULT_REASON = "Use the deterministic plan derived from trusted analysis counts."


def _field_reason(key: str, expected: dict) -> str:
    if key == "score_available":
        return "Score availability comes from the trusted audit context."
    if key == "eligible_group_count":
        return "Eligible group count comes from the trusted analysis counts."
    if key in ("compute_auroc", "auroc_reason"):
        return expected["auroc_reason"]
    if key == "reason":
        return "Use the explanation generated by the deterministic analysis rules."
    if key in ("method", "available", "bootstrap", "min_expected_count"):
        return expected["reason"]
    return _DEFAULT_REASON


def _diff_plan(
    proposed: JsonValue,
    expected: JsonValue,
    path: str = "$",
    reason: str = _DEFAULT_REASON,
) -> list[PlanCorrection]:
    corrections = []

    if isinstance(proposed, dict) and isinstance(expected, dict):
        for key, value in expected.items():
            child_path = f"{path}[{key!r}]"
            child_reason = _field_reason(key, expected)
            if key not in proposed:
                corrections.append(PlanCorrection(
                    operation="add", field_path=child_path,
                    proposed_value=None, corrected_value=value,
                    reason=f"Missing required field. {child_reason}",
                ))
            else:
                corrections.extend(_diff_plan(
                    proposed[key], value, child_path, child_reason,
                ))
        for key in proposed:
            if key not in expected:
                corrections.append(PlanCorrection(
                    operation="remove", field_path=f"{path}[{key!r}]",
                    proposed_value=proposed[key], corrected_value=None,
                    reason="Remove a field outside the deterministic plan contract.",
                ))
    elif isinstance(proposed, list) and isinstance(expected, list):
        for index in range(max(len(proposed), len(expected))):
            child_path = f"{path}[{index}]"
            if index >= len(proposed):
                corrections.append(PlanCorrection(
                    operation="add", field_path=child_path,
                    proposed_value=None, corrected_value=expected[index],
                    reason="Add a required item from the deterministic plan.",
                ))
            elif index >= len(expected):
                corrections.append(PlanCorrection(
                    operation="remove", field_path=child_path,
                    proposed_value=proposed[index], corrected_value=None,
                    reason="Remove an item outside the deterministic plan.",
                ))
            else:
                corrections.extend(_diff_plan(
                    proposed[index], expected[index], child_path, reason,
                ))
    elif type(proposed) is not type(expected) or proposed != expected:
        corrections.append(PlanCorrection(
            operation="replace", field_path=path,
            proposed_value=proposed, corrected_value=expected, reason=reason,
        ))

    return corrections


def guard_analysis_plan(
    proposed_plan: dict | AnalysisPlan,
    counts: list[AttributeAnalysisCounts],
    score_available: bool,
) -> GuardedAnalysisPlan:
    """Return a canonical plan plus all changes to a JSON-object proposal.

    Counts must come from the validated, policy-filtered Python pipeline.
    Proposal fields (including group counts and score availability) are never
    used as evidence. Lists and explanations follow deterministic ordering/text;
    normalizing a different order or explanation is also recorded.
    Non-JSON values and non-finite numbers raise instead of being stringified.
    """
    if isinstance(proposed_plan, AnalysisPlan):
        proposed_plan = proposed_plan.model_dump(mode="python")
    if not isinstance(proposed_plan, dict):
        raise TypeError("The proposed plan must be a JSON object or AnalysisPlan.")

    proposed = deepcopy(_JSON_VALUE.validate_python(proposed_plan, strict=True))
    expected = select_analyses(counts, score_available)
    corrections = _diff_plan(proposed, expected.model_dump(mode="json"))

    return GuardedAnalysisPlan(plan=expected, corrections=corrections)
